    <p>Şirket tarafından yürütülen kamera ile izleme ve kayıt altına alma faaliyeti, 5188 sayılı Özel Güvenlik Hizmetlerine Dair Kanun ve bu kanunun uygulanmasına ait yönetmeliğe uygun ve Şirket meşru menfaatine ve hukuki sebebe dayalı olarak sürdürülmektedir.</p>
<br/><br/>
    <h2>KVK Hukukuna Göre Güvenlik Kamerası ile İzleme Faaliyeti Yürütülmesi </h2><br/>
    <p>Şirket, bina ve tesislerinde güvenliğin sağlanması amacıyla, yürürlükte bulunan ilgili mevzuatta öngörülen amaçlarla ve KVK Kanunu’nda sayılan kişisel veri işleme şartlarına uygun olarak güvenlik kamerası izleme faaliyetinde bulunmaktadır. Kişisel veriler, binalarının güvenliğinin sağlanması kamera sistemleri vasıtasıyla KVK Kanunu’nun 5. maddesinde belirtilen kişisel veri işleme şartları çerçevesinde toplanmaktadır.<br/><br/>
Kanunun 5. maddesinde yer alan “veri sorumlusunun hukuki yükümlülüğünü yerine getirebilmesi için zorunlu olması” ve “ilgili kişinin temel hak ve özgürlüklerine zarar vermemek kaydıyla, veri sorumlusunun meşru menfaatleri için veri işlenmesinin zorunlu olması” hukuki sebebine dayanarak otomatik yolla işlenmektedir. 
</p>
<br/><br/>
    <h2>Kamera ile İzleme Faaliyetinin Duyurulması</h2><br/>
    <p>Şirket tarafından KVK Kanunu’nun 10. Maddesine uygun olarak, kişisel veri sahibi aydınlatılmaktadır.
Şirket genel hususlara ilişkin olarak yaptığı aydınlatmanın kamera ile izleme faaliyetine ilişkin birden fazla yöntem ile bildirimde bulunmaktadır. Böylelikle, kişisel veri sahibinin temel hak ve özgürlüklerine zarar verilmesinin engellenmesi, şeffaflığın ve kişisel veri sahibinin aydınlatılmasının sağlanması amaçlanmaktadır. Şirket tarafından kamera ile izleme faaliyetine yönelik olarak; izlemenin yapıldığı alanların girişlerine izleme yapılacağına ilişkin bildirim yazısı asılmaktadır.
</p>
