<br/><br/>
    <p>AVS Küresel Gemi Tedariği ve Yönetimi Anonim Şirketi (Bundan sonra ‘Şirket’ olarak anılacaktır.) tarafından bina tesis girişlerinde ve tesis içerisinde yapılan kişisel veri işleme faaliyetleri, Türkiye Cumhuriyeti Anayasası’na, Kişisel Verilen Korunması Kanunu’na (“KVK Kanun”) ve ilgili diğer mevzuata uygun bir biçimde yürütülmektedir. Kişisel Verilerin Korunması Kanunu’na (“KVK Kanun”) uyarınca veri sorumlusu olarak güvenliğin sağlanması amacıyla, Şirket binalarında, giriş-çıkış kapılarında, yemekhane, lokal, misafirhane, ziyaretçi bekleme salonu, otopark, güvenlik kulübesi, kat koridorları, bina dış cepheleri ve tesislerinde güvenlik kamerasıyla izleme faaliyeti ile misafirlerin, taşeronların ve bunlara ait araçların giriş çıkışlarının takibi ve kayıt altına alınması yoluyla Şirket tarafından veri sorumlusu sıfatı ile kişisel veri işleme faaliyetinde bulunulmaktadır.<br/><br/>
	Şirket hukuki, teknik ve ticari iş güvenliğinin temini amacıyla görüntü alınması yoluyla kişisel veri işlemektedir.
